import { test, expect } from '@playwright/test';

// Safe browser-only gate: no login, seeded users, database or API mutation.
// Real role/approval workflows are covered separately by disposable-DB E2E.
test.describe('Phase 3 browser security and responsive public surfaces', () => {
  test('protected management and worker pages redirect to login without credentials', async ({ page }) => {
    for (const path of ['/manager', '/admin', '/lead', '/worker', '/admin/permissions', '/manager/reports']) {
      await page.goto('/#' + path);
      await expect(page).toHaveURL(/#\/login(?:\?|$)/);
      const keys = await page.evaluate(() => Object.keys(localStorage).filter(k => /token/i.test(k)));
      expect(keys, 'no token generated by protected redirect').toEqual([]);
    }
  });

  test('login form stays inside mobile viewport and has no horizontal overflow', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/#/login');
    await expect(page.getByPlaceholder('Nhập mã nhân viên')).toBeVisible();
    const widths = await page.evaluate(() => ({
      viewport: document.documentElement.clientWidth,
      page: document.documentElement.scrollWidth,
    }));
    expect(widths.page).toBeLessThanOrEqual(widths.viewport + 1);
  });

  test('login keyboard input respects the configured 20-character limit', async ({ page }) => {
    await page.goto('/#/login');
    const field = page.getByPlaceholder('Nhập mã nhân viên');
    await expect(field).toBeVisible();
    await field.focus();
    await expect(field).toBeFocused();
    await page.keyboard.type('E2E-SYNTHETIC-NO-SUBMIT');
    await expect(field).toHaveAttribute('maxlength', '20');
    await expect(field).toHaveValue('E2E-SYNTHETIC-NO-SUB');
  });
});
